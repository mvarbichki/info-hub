# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

# Chosen by environment variables:
# - MARIADB_DB set: MariaDB/MySQL, e.g. shared cPanel hosting (needs requirements-mariadb.txt).
# - POSTGRES_DB set: PostgreSQL, the Docker variant (.env).
# - neither: SQLite for local development.
if os.environ.get("MARIADB_DB"):
    # The database must be utf8mb4 with this collation (MariaDB's own default is latin1, which
    # can't store Cyrillic); the connection uses the same collation, else text comparisons fail.
    # Checked before `migrate` by home/checks.py.
    MARIADB_COLLATION = os.environ.get("MARIADB_COLLATION", "utf8mb4_unicode_ci")
    try:
        import MySQLdb  # noqa: F401  (mysqlclient, Django's recommended driver)
    except ImportError:
        # Shared hosting often has no C compiler to build mysqlclient: use the pure-Python PyMySQL
        # in its place. It reports an old mysqlclient version, which Django would refuse.
        import pymysql

        pymysql.version_info = (2, 2, 1, "final", 0)
        pymysql.install_as_MySQLdb()
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.mysql",
            "NAME": os.environ["MARIADB_DB"],
            "USER": os.environ.get("MARIADB_USER", "infohub"),
            "PASSWORD": os.environ.get("MARIADB_PASSWORD", ""),
            "HOST": os.environ.get("MARIADB_HOST", "localhost"),
            "PORT": os.environ.get("MARIADB_PORT", "3306"),
            "CONN_MAX_AGE": 60,
            "OPTIONS": {
                "charset": "utf8mb4",
                "collation": MARIADB_COLLATION,
                # Strict mode: too-long or invalid values raise an error instead of being cut silently.
                # InnoDB: some hosts make MyISAM tables by default (no transactions, keys too short).
                "init_command": "SET sql_mode='STRICT_TRANS_TABLES', default_storage_engine=INNODB",
            },
            "TEST": {"CHARSET": "utf8mb4", "COLLATION": MARIADB_COLLATION},
        }
    }
    # Wagtail's WorkflowState has a conditional unique constraint MariaDB can't create.
    # Workflows aren't used here (posts are published directly).
    SILENCED_SYSTEM_CHECKS = ["models.W036"]
elif os.environ.get("POSTGRES_DB"):
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": os.environ["POSTGRES_DB"],
            "USER": os.environ.get("POSTGRES_USER", "infohub"),
            "PASSWORD": os.environ.get("POSTGRES_PASSWORD", ""),
            "HOST": os.environ.get("POSTGRES_HOST", "db"),
            "PORT": os.environ.get("POSTGRES_PORT", "5432"),
        }
    }
    # Wagtail's search index uses PostgreSQL's full-text fields there; Django refuses to start
    # without this app (postgres.E005).
    INSTALLED_APPS.append("django.contrib.postgres")
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }


